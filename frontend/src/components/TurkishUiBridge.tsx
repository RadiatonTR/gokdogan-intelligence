/**
 * Compatibility translator for legacy dashboard chrome that predates the i18n layer.
 *
 * It intentionally translates only short, exact UI labels / attributes. Article
 * titles, intelligence records, callsigns, source names and free-form telemetry are
 * never machine-translated here, so source fidelity is preserved.
 */
function flattenTranslations(value: unknown, prefix = '', out: Record<string, string> = {}): Record<string, string> {
  if (!value || typeof value !== 'object') return out;
  for (const [key, child] of Object.entries(value as Record<string, unknown>)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (typeof child === 'string') out[path] = child;
    else flattenTranslations(child, path, out);
  }
  return out;
}

