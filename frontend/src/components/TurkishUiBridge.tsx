function translateUiValue(value: string): string {
  const trimmed = value.trim();
  const exact = EXACT[trimmed] || I18N_REVERSE[trimmed];
  if (exact) return exact;
  let next = trimmed;
  next = next.replace(/ALERT LVL\s*:?\s*(\d+)/gi, 'UYARI SEVİYESİ $1');
  next = next.replace(/ACTIVE THREATS IN AREA/gi, 'BÖLGEDE AKTİF TEHDİT');
  next = next.replace(/(\d+) snapshots? ready/gi, '$1 anlık görüntü hazır');
  next = next.replace(/snapshot(s)?/gi, (m) => m.toLowerCase().endsWith('s') ? 'anlık görüntüler' : 'anlık görüntü');
  for (const [from, to] of UI_PHRASES) {
    if (next.includes(from)) next = next.replace(from, to);
  }
  return next;
}

const ATTRS = ['title', 'aria-label', 'placeholder'] as const;

function translateTextNode(node: Text): void {
  const parent = node.parentElement;
  if (!parent) return;
  const raw = node.nodeValue || '';
  const trimmed = raw.trim();
  const translated = translateUiValue(trimmed);
  if (!translated || translated === trimmed) return;
  const lead = raw.match(/^\s*/)?.[0] ?? '';
  const trail = raw.match(/\s*$/)?.[0] ?? '';
  node.nodeValue = `${lead}${translated}${trail}`;
}

function translateElement(el: Element): void {
  for (const attr of ATTRS) {
    const current = el.getAttribute(attr);
    if (!current) continue;
    const translated = translateUiValue(current.trim());
    if (translated && translated !== current.trim()) el.setAttribute(attr, translated);
  }

  for (const child of Array.from(el.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) translateTextNode(child as Text);
  }
}

function translateTree(root: ParentNode): void {
  if (root instanceof Element) translateElement(root);
  root.querySelectorAll?.('button,label,option,summary,th,td,legend,h1,h2,h3,h4,h5,h6,span,p,div,a,li,[role="button"],[role="tab"],[title],[aria-label],[placeholder]')
    .forEach(translateElement);
}

export default function TurkishUiBridge() {
  const { locale } = useTranslation();

  useEffect(() => {
    if (locale !== 'tr' || typeof document === 'undefined') return;
    translateTree(document.body);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        for (const node of Array.from(mutation.addedNodes)) {
          if (node instanceof Element) translateTree(node);
          else if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text);
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [locale]);

  return null;
}
